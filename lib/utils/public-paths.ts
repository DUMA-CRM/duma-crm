/**
 * Which paths `proxy.ts` lets through without a session cookie. Everything else
 * redirects to sign-in, so a page missing from here is invisible to every
 * visitor and every crawler — it renders the sign-in screen instead.
 *
 * Pure and dependency-free so the edge proxy and the unit tests share one copy.
 */

// The app's own public surfaces.
//
// '/be' is the same-origin API proxy: it MUST stay exempt or unauthenticated
// API calls (sign-in itself!) get redirected to the sign-in HTML page, which
// then fails JSON parsing in the client. The API enforces its own auth.
// '/ingest' is product analytics (next.config.ts): the sign-in page reports too.
// '/api/cms-webhook' is the CMS's signed callback that refreshes the blog — it checks its own signature.
const APP_PUBLIC_PATHS = ['/sign-in', '/sign-up', '/forgot-password', '/reset-password', '/verify-email', '/order', '/book', '/f', '/privacy', '/terms', '/api/auth', '/api/cms-webhook', '/be', '/ingest'];

// The marketing site's sections, reserved up front — including ones with no
// page yet — so a new page under them is public the day it ships rather than
// the day someone remembers this list. None may share a first segment with an
// app route in app/(crm): that route would become reachable without a session
// cookie (the CRM layout still checks the session, but the proxy layer is gone).
export const MARKETING_PATHS = [
  '/welcome',
  '/features',
  '/solutions',
  '/compare',
  '/alternatives',
  '/pricing',
  '/why-duma',
  '/about',
  '/contact',
  '/security',
  '/changelog',
  '/tools',
  '/developers',
  '/blog',
  '/glossary',
  // Generated by app/sitemap.ts, app/robots.ts and app/opengraph-image.tsx.
  // Crawlers and link unfurlers have no session; the share card has no file
  // extension, so the proxy matcher's static-file exemption misses it.
  '/sitemap.xml',
  '/robots.txt',
  '/opengraph-image',
  // For AI assistants and answer engines: app/llms.txt and app/llms-full.txt (lib/blog/llms.ts).
  '/llms.txt',
  '/llms-full.txt',
] as const;

export const PUBLIC_PATHS: readonly string[] = [...APP_PUBLIC_PATHS, ...MARKETING_PATHS];

/**
 * '/' is matched exactly — a startsWith('/') check matches every path and
 * disables the guard entirely. The rest match themselves and their subpaths,
 * never a sibling that merely shares the prefix ('/blogger' is not '/blog').
 */
export function isPublicPath(pathname: string): boolean {
  return pathname === '/' || PUBLIC_PATHS.some((p) => pathname === p || pathname.startsWith(`${p}/`));
}
